import { mkdtemp, readFile, readdir, rm, stat } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { ConfigError, loadConfig } from "../../src/config/load.js";
import { ContextSchema, type ContextInput, SourcesSchema, type SourcesInput } from "../../src/config/schema.js";
import { writeConfig } from "../../src/config/write.js";

const context: ContextInput = {
  version: 1,
  project: { name: "app", description: "Line one: with a colon\nand a second line" },
  problems: ["Next.js breaking changes", "日本語の課題"],
  language: "Japanese",
};
const sources: SourcesInput = {
  version: 1,
  feeds: [
    { id: "next", type: "github", name: "Next.js", repo: "vercel/next.js" },
    { id: "blog", type: "rss", name: "Blog #1", url: "https://example.com/feed?x=1&y=2" },
  ],
  queries: [{ id: "q", query: "Qwen release", topic: "news" }],
};

let dir: string;
let previousUmask: number;

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "pochi-write-"));
  previousUmask = process.umask(0o022);
});

afterEach(async () => {
  process.umask(previousUmask);
  await rm(dir, { recursive: true, force: true });
});

describe("writeConfig", () => {
  it("writes files that load back to the same config", async () => {
    const target = join(dir, "nested", "config");
    const paths = await writeConfig(target, { context, sources });
    expect(paths).toEqual({ contextPath: join(target, "context.yml"), sourcesPath: join(target, "sources.yml") });

    const loaded = await loadConfig({ configDir: target, env: {} });
    expect(loaded.context).toEqual(ContextSchema.parse(context));
    expect(loaded.sources).toEqual(SourcesSchema.parse(sources));
  });

  it("writes the input as given, without expanding defaults", async () => {
    const { contextPath } = await writeConfig(dir, { context, sources });
    const text = await readFile(contextPath, "utf8");
    expect(text).toMatch(/^# Generated by pochi init/);
    expect(text).toContain("SLACK_WEBHOOK_URL");
    expect(text).not.toContain("maxItemsPerCall");
  });

  it("creates files readable by the owner only", async () => {
    const { contextPath, sourcesPath } = await writeConfig(dir, { context, sources });
    for (const path of [contextPath, sourcesPath]) {
      expect((await stat(path)).mode & 0o777).toBe(0o600);
    }
  });

  it("overwrites existing files and leaves no temporary files", async () => {
    await writeConfig(dir, { context, sources });
    await writeConfig(dir, { context: { ...context, language: "English" }, sources });
    expect((await readdir(dir)).sort()).toEqual(["context.yml", "sources.yml"]);
    expect((await loadConfig({ configDir: dir, env: {} })).context.language).toBe("English");
  });

  it("writes nothing when either input is invalid", async () => {
    const err = await writeConfig(dir, {
      context: { ...context, problems: [] },
      sources: { version: 1 },
    }).then(
      () => undefined,
      (e: unknown) => e,
    );
    expect(err).toBeInstanceOf(ConfigError);
    expect((err as ConfigError).message.split("\n")).toEqual([
      "context: problems: must have at least 1 item",
      "sources: (root): at least one feed or query is required",
    ]);
    expect(await readdir(dir)).toEqual([]);
  });
});
