import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { setTimeout as sleep } from "node:timers/promises";
import { ConfigError } from "../config/load.js";
import { type Calendar, CalendarError, type Field } from "./calendar.js";
import type { ExecFn } from "./exec.js";
import type { Job, Scheduler } from "./types.js";

// One dictionary per combination; past this the calendar is better served by cron.
const MAX_INTERVALS = 100;
const KEYS = [
  ["Month", "month"],
  ["Day", "dayOfMonth"],
  ["Weekday", "weekday"],
  ["Hour", "hour"],
  ["Minute", "minute"],
] as const;

/** A per-user LaunchAgent. A run missed while the Mac slept happens on wake, once. */
export function launchdScheduler(deps: { exec: ExecFn; home: string; uid: number; retryDelayMs?: number }): Scheduler {
  const plistPath = (job: Job) => join(deps.home, "Library", "LaunchAgents", `${job.id}.plist`);
  const domain = `gui/${deps.uid}`;
  return {
    name: "launchd",
    zone: "local",
    location: plistPath,
    render(job, cal, summary) {
      const intervals = startCalendarInterval(cal);
      return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
        `<!-- Generated by pochi schedule install: ${comment(summary)} -->`,
        '<plist version="1.0">',
        "<dict>",
        ...entry("Label", str(job.id)),
        "  <key>ProgramArguments</key>",
        "  <array>",
        ...job.argv.map((a) => `    ${str(a)}`),
        "  </array>",
        ...entry("WorkingDirectory", str(job.cwd)),
        "  <key>EnvironmentVariables</key>",
        "  <dict>",
        `    <key>PATH</key>`,
        `    ${str(job.path)}`,
        "  </dict>",
        "  <key>StartCalendarInterval</key>",
        "  <array>",
        ...intervals.map(
          (d) => `    <dict>${d.map(([k, v]) => `<key>${k}</key><integer>${v}</integer>`).join("")}</dict>`,
        ),
        "  </array>",
        ...entry("StandardOutPath", str(job.logPath)),
        ...entry("StandardErrorPath", str(job.logPath)),
        "</dict>",
        "</plist>",
        "",
      ].join("\n");
    },
    async install(job, content) {
      const path = plistPath(job);
      await mkdir(dirname(path), { recursive: true });
      // An older version of the job may be loaded; it keeps its old schedule until booted out.
      await deps.exec("launchctl", ["bootout", `${domain}/${job.id}`]);
      await writeFile(path, content, { mode: 0o644 });
      let r = await deps.exec("launchctl", ["bootstrap", domain, path]);
      if (r.code !== 0) {
        // Right after a bootout, launchd can still be tearing the job down (error 5).
        await sleep(deps.retryDelayMs ?? 1000);
        r = await deps.exec("launchctl", ["bootstrap", domain, path]);
      }
      if (r.code !== 0) {
        throw new ConfigError(`launchctl bootstrap failed (${r.code}): ${r.stderr.trim() || r.stdout.trim()}`);
      }
      return ["A run missed while the Mac is asleep happens when it wakes; one missed while it is off does not."];
    },
    async uninstall(job) {
      const path = plistPath(job);
      const unloaded = (await deps.exec("launchctl", ["bootout", `${domain}/${job.id}`])).code === 0;
      const existed = await rm(path).then(
        () => true,
        (err: NodeJS.ErrnoException) => {
          if (err.code === "ENOENT") return false;
          throw err;
        },
      );
      return unloaded || existed;
    },
    async inspect(job) {
      const content = await readFile(plistPath(job), "utf8").catch((err: NodeJS.ErrnoException) => {
        if (err.code === "ENOENT") return undefined;
        throw err;
      });
      const loaded = (await deps.exec("launchctl", ["print", `${domain}/${job.id}`])).code === 0;
      return { content, loaded };
    },
  };
}

/**
 * One dictionary per combination of the restricted fields; a missing key matches everything.
 * launchd requires every key in a dictionary to match, so day of month and weekday together
 * cannot keep cron's "either" and are refused.
 */
export function startCalendarInterval(cal: Calendar): [string, number][][] {
  if (cal.dayOfMonth !== "*" && cal.weekday !== "*") {
    throw new CalendarError(
      "launchd cannot run on a day of the month or a weekday (cron's rule when both are set); use one, or --backend cron",
    );
  }
  let dicts: [string, number][][] = [[]];
  for (const [key, name] of KEYS) {
    const field: Field = cal[name];
    if (field === "*") continue;
    dicts = dicts.flatMap((d) => field.map((v) => [...d, [key, v] as [string, number]]));
    if (dicts.length > MAX_INTERVALS) {
      throw new CalendarError(`the schedule needs more than ${MAX_INTERVALS} launchd intervals; use --backend cron`);
    }
  }
  return dicts;
}

function entry(key: string, value: string): string[] {
  return [`  <key>${key}</key>`, `  ${value}`];
}

function str(s: string): string {
  return `<string>${s.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;")}</string>`;
}

// "--" may not appear inside an XML comment.
function comment(s: string): string {
  return s.replaceAll("--", "- -");
}
