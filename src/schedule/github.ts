import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { toCron } from "./calendar.js";
import type { Job, Scheduler } from "./types.js";

export const WORKFLOW_PATH = ".github/workflows/daily_briefing.yml";

/**
 * A workflow in the checkout. It only takes effect once committed and pushed to the default
 * branch, which is left to the user. Config and keys come from repository secrets.
 */
export function githubScheduler(): Scheduler {
  const workflowPath = (job: Job) => join(job.cwd, WORKFLOW_PATH);
  return {
    name: "github",
    zone: "UTC",
    location: workflowPath,
    render(_job, cal, summary) {
      return workflow(toCron(cal), summary);
    },
    async install(job, content) {
      const path = workflowPath(job);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, content);
      return [
        `Commit and push ${WORKFLOW_PATH} to the default branch; scheduled workflows run only there.`,
        "Set the repository secrets it reads (gh secret set NAME): POCHI_CONTEXT_YAML and POCHI_SOURCES_YAML (the config files' contents), ANTHROPIC_API_KEY, and SLACK_WEBHOOK_URL or TAVILY_API_KEY when used.",
        "Try it from the Actions tab with dry_run checked before the first scheduled run.",
      ];
    },
    async uninstall(job) {
      return rm(workflowPath(job)).then(
        () => true,
        (err: NodeJS.ErrnoException) => {
          if (err.code === "ENOENT") return false;
          throw err;
        },
      );
    },
    async inspect(job) {
      const content = await readFile(workflowPath(job), "utf8").catch((err: NodeJS.ErrnoException) => {
        if (err.code === "ENOENT") return undefined;
        throw err;
      });
      return { content };
    },
  };
}

// Inputs reach the shell through env, never through ${{ }} inside a script.
function workflow(cron: string, summary: string): string {
  return `# Generated by \`pochi schedule install --backend github\`. To change when it runs, edit
# schedule in context.yml and install again.
name: Briefing

on:
  schedule:
    # ${summary}
    - cron: "${cron}"
  workflow_dispatch:
    inputs:
      dry_run:
        description: Print the briefing instead of posting it, and leave the state file as is
        type: boolean
        default: false

permissions:
  contents: write

concurrency:
  group: briefing
  cancel-in-progress: false

jobs:
  briefing:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v7
      - uses: actions/setup-node@v7
        with:
          node-version: 24
          cache: npm
      - run: npm ci
      - run: npm run build
      - name: Run pochi
        env:
          POCHI_CONTEXT_YAML: \${{ secrets.POCHI_CONTEXT_YAML }}
          POCHI_SOURCES_YAML: \${{ secrets.POCHI_SOURCES_YAML }}
          ANTHROPIC_API_KEY: \${{ secrets.ANTHROPIC_API_KEY }}
          TAVILY_API_KEY: \${{ secrets.TAVILY_API_KEY }}
          SLACK_WEBHOOK_URL: \${{ secrets.SLACK_WEBHOOK_URL }}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          DRY_RUN: \${{ inputs.dry_run }}
        run: |
          if [ "$DRY_RUN" = "true" ]; then
            node dist/pochi.mjs run --dry-run
          else
            node dist/pochi.mjs run
          fi
      # Also after a failed run: what it delivered before failing is recorded and must not repeat.
      - name: Commit the state file
        if: \${{ !cancelled() && inputs.dry_run != true }}
        run: |
          [ -f state/notified.json ] || exit 0
          git add -f state/notified.json
          if git diff --cached --quiet; then exit 0; fi
          git config user.name "github-actions[bot]"
          git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
          git commit -m "chore(state): record notified items [skip ci]"
          git pull --rebase
          git push
`;
}
